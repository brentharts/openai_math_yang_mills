"""The knowledge graph (knowledgebase.py) checked against the other models, and what it derives.

Three parts.

1. Structure. The tables copied from RosettaMath are consistent (every reading names a known
   quantity, every link joins two known equations, every dimension string parses) and every
   join the library yields is an identity once the pivot is substituted back.

2. Bridges. Three knowledge-base entries that RosettaMath drew from this repository's scripts
   are checked against the sympy models of the manuscripts, so the two repositories are tested
   against each other rather than each against itself:
     entry 216  Kosterlitz coupling and fugacity flow  vs the explicit solution k cot kw, k csc kw
     entry 215  asymptotic-freedom mass scaling, transmutation slope, spin block coupling
     entry 271  magnon dispersion and the Bloch magnon density with its lattice correction

3. Compositions. A curated set of pairwise joins, generated by knowledgebase.join(): the
   equations are rearranged and eliminated by sympy, and each result is registered as a
   'derived' equation. Only the pivots in REGISTERED_PIVOTS are registered.

Not tested: that RosettaMath's entries quote their sources correctly, beyond the three bridges
above; and the physics behind a join (the same letter, read the same way, is taken to be the
same variable).
"""
import sympy as sp

import knowledgebase as kb
from eqlib import Equation, check, register

NAME = "knowledge"

# Pivots whose joins are registered as equations: the repository's themes, statistical mechanics,
# lattice scaling and running couplings. The library yields many more joins (kb.all_joins()); the
# rest are counted in the document and not registered. Some, such as m c^2 = (1/2) m v^2 on
# energy, state only a condition (the rest energy equals the kinetic energy), which is a true
# consequence of the two laws and not a law.
REGISTERED_PIVOTS = {"entropy", "temperature", "lattice mass", "inverse coupling",
                     "spin transmutation slope", "gauge transmutation slope",
                     "confining string tension", "unification scale"}
RESEARCH = "RosettaMath rosettaphys.py"


def _src(*names, script=""):
    quoted = " and ".join(f"'{n}'" for n in names)
    return f"{RESEARCH}: {quoted}" + (f" (cites {script})" if script else "")


def build_and_verify():
    # ---- 1. structure ------------------------------------------------------------------
    for item in kb.selftest():
        check(NAME, f"knowledge base selftest: {item}", True)
    lib = kb.library()
    check(NAME, "the copied library has 155 equations, 150 quantities and 125 readings tables",
          (len(lib.equations), len(lib.quantities), len(kb.READINGS_DATA)) == (155, 150, 125))

    # ---- 2a. entry 216: Kosterlitz-Thouless flow ------------------------------------------
    x, y, l = sp.symbols("x y l")
    X_, Y_, W_, k_ = sp.symbols("X Y w k", positive=True)
    sx, sl, fx = kb.read_rate(kb.equation("Kosterlitz coupling flow").latex)
    sy, sl2, fy = kb.read_rate(kb.equation("Kosterlitz fugacity flow").latex)
    check(NAME, "both Kosterlitz flows are read as rates in the same variable", sl == sl2 == l)
    eq_kt = register(NAME, Equation(
        key="kb_kt_flow", entry="216",
        title="Kosterlitz flow, from the knowledge base",
        source_kind="knowledge-base",
        source=_src("Kosterlitz coupling flow", "Kosterlitz fugacity flow", script="tools/kt_flow.py"),
        latex_str=r"\frac{dx}{dl}=-y^{2},%%BR%%\frac{dy}{dl}=-xy",
        notes="Written in RosettaMath's variables: x is the stiffness deviation, y the vortex "
              "fugacity, l the logarithm of the length scale. It is the paper's eq. (1.6) "
              "(X' = -Y^2, Y' = -XY) with X, Y, w renamed x, y, l.",
    ))
    eq_kt.cites = ["rosettamath", "oai-xy-essential"]
    eq_kt.see = [(kb.kb_label("Kosterlitz coupling flow"), "Kosterlitz coupling flow",
                  kb.wikipedia_url(kb.equation("Kosterlitz coupling flow").slug)),
                 (kb.kb_label("Kosterlitz fugacity flow"), "Kosterlitz fugacity flow",
                  kb.wikipedia_url(kb.equation("Kosterlitz fugacity flow").slug)),
                 ("eq:kt_limiting_flow", "the paper's limiting flow and its solution", None),
                 ("eq:kt_recursion", "the paper's recursion", None)]
    Xs, Ys = k_ * sp.cot(k_ * W_), k_ * sp.csc(k_ * W_)
    sub = {x: Xs, y: Ys}
    check(NAME, "the paper's solution X = k cot kw solves dx/dl = -y^2 of the knowledge base",
          sp.simplify(sp.diff(Xs, W_) - fx.subs(sub)) == 0, eq=eq_kt)
    check(NAME, "the paper's solution Y = k csc kw solves dy/dl = -x y of the knowledge base",
          sp.simplify(sp.diff(Ys, W_) - fy.subs(sub)) == 0, eq=eq_kt)
    euler = sp.Matrix([x + fx, y + fy])           # one step of size 1 of the flow
    check(NAME, "one unit step of the flow is the paper's recursion (x, y) -> (x - y^2, y - x y), eq. (1.4)",
          sp.simplify(euler - sp.Matrix([x - y**2, y - x * y])) == sp.zeros(2, 1), eq=eq_kt)
    check(NAME, "the flow conserves x^2 - y^2 (the first integral behind X^2 - Y^2 = -k^2)",
          sp.simplify(2 * x * fx - 2 * y * fy) == 0, eq=eq_kt)

    # ---- 2b. entry 215: asymptotic freedom and blocking ------------------------------------
    beta, N, C, ell = sp.symbols("beta N C ell", positive=True)
    mass_kb = kb.equation("Asymptotic-freedom mass scaling").relation()
    mass = beta ** (1 / (N - 2)) * sp.exp(-2 * sp.pi * beta / (N - 2))      # on_scaling.py, on_mass_af
    eq_af = register(NAME, Equation(
        key="kb_af_scaling", entry="215",
        title="Asymptotic-freedom scaling, transmutation slope and blocking, from the knowledge base",
        source_kind="knowledge-base",
        source=_src("Asymptotic-freedom mass scaling", "Spin-model transmutation slope",
                    "Spin block coupling", script="tools/on_model_mc.py"),
        latex_str=(r"m=C\,\beta^{\frac1{N-2}}\exp\!\Bigl(-\frac{2\pi\beta}{N-2}\Bigr),%%BR%%"
                   r"r_s=\frac{2\pi}{N-2},\qquad \beta_1=\beta_0-\frac{\ln \ell}{r_s}"),
        notes="Leading asymptotic-freedom form only; C is the non-universal constant in front. "
              "m is the lattice mass, beta the spin inverse temperature, ell the linear blocking factor.",
    ))
    eq_af.cites = ["rosettamath", "oai-o4-mass", "oai-o3-limit"]
    eq_af.see = [(kb.kb_label(n), n, kb.wikipedia_url(kb.equation(n).slug)) for n in
                 ("Asymptotic-freedom mass scaling", "Spin-model transmutation slope", "Spin block coupling")] + [
                 ("eq:on_mass_af", "the leading form of the O(N) mass in entry 215", None),
                 ("eq:on_log_slope", "its logarithmic slope", None)]
    m_sym, C_sym = sp.Symbol("m"), sp.Symbol("C")
    mass_rhs = mass_kb.rhs.xreplace({s: sp.Symbol(s.name, positive=True) for s in mass_kb.rhs.free_symbols})
    check(NAME, "the knowledge-base mass law equals this repository's on_mass_af up to the constant C",
          sp.simplify(mass_rhs / sp.Symbol("C", positive=True) - mass) == 0, eq=eq_af)
    r_s = kb.solve_for("Spin-model transmutation slope", "spin transmutation slope").expr
    r_s = r_s.xreplace({s: sp.Symbol(s.name, positive=True) for s in r_s.free_symbols})
    slope = sp.limit(-sp.diff(sp.log(mass), beta), beta, sp.oo)
    check(NAME, "-d ln m / d beta tends to the knowledge base's transmutation slope 2 pi / (N - 2)",
          sp.simplify(slope - r_s) == 0, eq=eq_af)
    block = kb.solve_for("Spin block coupling", "blocked spin inverse temperature").expr
    b0 = sp.Symbol("beta_0", positive=True)
    block = block.xreplace({sp.Symbol("beta_0"): b0, sp.Symbol("ell"): ell, sp.Symbol("r_s"): r_s})
    shrink = sp.simplify(sp.powsimp(sp.expand_power_base(
        sp.simplify(mass.subs(beta, block) / mass.subs(beta, b0)), force=True), force=True))
    check(NAME, "blocking by ell lowers beta so that m(beta_1)/m(beta_0) -> ell as beta_0 -> infinity "
                "(the correlation length shrinks by ell)",
          sp.simplify(sp.limit(shrink, b0, sp.oo) - ell) == 0, eq=eq_af)

    # ---- 2c. entry 271: Bloch ----------------------------------------------------------------
    k1, k2, k3 = sp.symbols("k1 k2 k3", real=True)
    eps = 2 * sum(1 - sp.cos(kk) for kk in (k1, k2, k3))
    eq_disp = register(NAME, Equation(
        key="kb_magnon_dispersion", entry="271",
        title="Nearest-neighbour magnon dispersion, from the knowledge base",
        source_kind="knowledge-base",
        source=_src("Magnon dispersion", script="tools/bloch_law.py"),
        latex_str=r"\epsilon(k)=2\sum_{a=1}^{3}\bigl(1-\cos k_a\bigr)",
        notes="Simple cubic lattice, in units of the exchange; the sum runs over the three axes.",
    ))
    eq_disp.cites = ["rosettamath", "oai-bloch", "oai-bloch-correction"]
    eq_disp.see = [(kb.kb_label("Magnon dispersion"), "Magnon dispersion",
                    kb.wikipedia_url(kb.equation("Magnon dispersion").slug)),
                   ("eq:bloch_dispersion", "the dispersion of the manuscripts", None)]
    quad = sum(sp.series(eps, kk, 0, 4).removeO().subs({o: 0 for o in (k1, k2, k3) if o != kk}) for kk in (k1, k2, k3))
    check(NAME, "the dispersion is |k|^2 + O(k^4) near 0 (the quadratic part Bloch's T^{3/2} law rests on)",
          sp.simplify(sp.expand(quad - 2 * (k1**2 + k2**2 + k3**2) / 2)) == 0, eq=eq_disp)

    n_kb = kb.equation("Bloch magnon density").relation()
    A0, A1, xs = sp.symbols("A_0 A_1 x", positive=True)
    n_rhs = n_kb.rhs.xreplace({s: sp.Symbol(s.name, positive=True) for s in n_kb.rhs.free_symbols})
    paper = (sp.zeta(sp.Rational(3, 2)) / (8 * sp.pi ** sp.Rational(3, 2)) * xs ** sp.Rational(-3, 2)
             + 3 * sp.zeta(sp.Rational(5, 2)) / (128 * sp.pi ** sp.Rational(3, 2)) * xs ** sp.Rational(-5, 2))
    eq_bloch = register(NAME, Equation(
        key="kb_bloch_density", entry="271",
        title="Magnon density with its lattice correction, from the knowledge base",
        source_kind="knowledge-base",
        source=_src("Bloch magnon density", script="tools/bloch_law.py"),
        latex_str=(r"n=A_0\,x^{-3/2}+A_1\,x^{-5/2},\qquad x=\beta S,%%BR%%"
                   r"A_0=\frac{\zeta(3/2)}{8\pi^{3/2}},\quad A_1=\frac{3\,\zeta(5/2)}{128\pi^{3/2}}"),
        notes="The coefficients are those of the first lattice correction (Corollary 1.2 of the "
              "lattice-correction paper), supplied by bloch_law.py; the knowledge base states the "
              "form and leaves A_0, A_1 as unnamed coefficients.",
    ))
    eq_bloch.cites = ["rosettamath", "oai-bloch", "oai-bloch-correction"]
    eq_bloch.see = [(kb.kb_label("Bloch magnon density"), "Bloch magnon density",
                     kb.wikipedia_url(kb.equation("Bloch magnon density").slug)),
                    ("eq:bloch_correction_corollary", "Corollary 1.2, the first lattice correction", None)]
    sub_a = {A0: sp.zeta(sp.Rational(3, 2)) / (8 * sp.pi ** sp.Rational(3, 2)),
             A1: 3 * sp.zeta(sp.Rational(5, 2)) / (128 * sp.pi ** sp.Rational(3, 2))}
    sym_x = sp.Symbol("x", positive=True)
    form = n_rhs.subs({sp.Symbol("A_0", positive=True): A0, sp.Symbol("A_1", positive=True): A1})
    check(NAME, "the knowledge base's density, with the paper's A_0 and A_1, is the paper's two-term expansion",
          sp.simplify(form.subs(sub_a) - paper.subs(xs, sym_x)) == 0, eq=eq_bloch)
    check(NAME, "the density is positive and decreasing in x for these coefficients",
          all(sp.N(sub_a[a]) > 0 for a in (A0, A1))
          and sp.simplify(sp.diff(paper, xs)).subs(xs, 5).evalf() < 0, eq=eq_bloch)

    # tie the cross-checked equations into the graph (the 'models' edges)
    g = kb.graph()
    for eqobj, names in ((eq_kt, ["Kosterlitz coupling flow", "Kosterlitz fugacity flow"]),
                         (eq_af, ["Asymptotic-freedom mass scaling", "Spin-model transmutation slope",
                                  "Spin block coupling"]),
                         (eq_disp, ["Magnon dispersion"]), (eq_bloch, ["Bloch magnon density"])):
        if g.get("registered", eqobj.key) is None:
            node = g.add(kb.Node("registered", eqobj.key, eqobj.key))
            for n in names:
                g.link(kb.MODELS, node, kb.equation(n).node, "cross-checked in models/knowledge.py")

    # ---- 3. compositions ---------------------------------------------------------------------
    joins = kb.all_joins()
    registered = [j for j in joins if j.pivot in REGISTERED_PIVOTS]
    check(NAME, f"the library yields {len(joins)} verified pairwise joins; {len(registered)} on "
                "the repository's pivots are registered", len(registered) > 0)
    for j in registered:
        eq = register(NAME, kb.join_to_equation(j))
        for passed in j.verify():
            check(NAME, passed, True, eq=eq)
