"""SO(10), SU(4), the frame-Higgs 40 and Spin(1,3) against SU(3)_M, from brentharts/chirality-standard-model.

The author's `lisi/` directory (match_e8_d7.py, check_frame_higgs.py, check_triality_su4.py, THEORY.md and
README.md "Spin(1,3) against SU(3)_M") describes how the SO(10) of one Standard Model generation, the
SU(4) that centralises it and the horizontal SU(3)_M sit in one E8 root system. models/chirality_lisi.py
already rebuilds E8 and its gradings. This module continues from those roots, copies no script, and
reads off by counting:

  * E8 > D7 x U(1) (the node 1 grading) and D7 > D5 x D2: the 84 roots of D7 are 40 (D5) + 4 (D2 = A1 x A1)
    + 40, and the 40 are 10 weights of the D5 vector times the 4 weights of (2, 2): the frame-Higgs (10, (2,2));
    each of the two 14-root levels is (1, 10) + (4, 1);
  * E8 > D5 x A3 inside a D5 of E6: 240 = 40 + 12 + 60 + 2 . 64, the root count of
    248 = (45,1) + (1,15) + (10,6) + (16,4) + (16bar,4bar), with the multiplicities 6, 4, 4;
  * the horizontal A2 of the family grading lies inside the A3 = the centraliser of the D5, and the three
    placements of A1 x A1 in that A3 each have exactly one factor inside the A2 (the repository's statement
    that every su(2) x su(2) in SU(4) shares exactly one su(2) with SU(3)_M).

Quoted, not rederived: the Clifford-algebra side (Cl(11,3), the Majorana-Weyl 64, which su(2) is "left"),
the table of how many of the three 16s lie in the physical 64, the explicit triality T' and its hexagon, the
Distler-Garibaldi real-form argument. The repository says these depend on the real form or on explicit
matrices, which a root computation cannot see. Nothing here says the Standard Model is inside E8.
"""
from collections import Counter

import sympy as sp

from eqlib import Equation, check, register
from models import chirality_lisi as cl

NAME = "chirality_frame"
ENTRY = "chirality-lisi"
REPO = "brentharts/chirality-standard-model"
THEORY = f"{REPO}: lisi/THEORY.md and lisi/README.md"

ip, N = cl.ip, cl.N


def positive(r):
    return all(x >= 0 for x in r)


def simple_roots(roots):
    """Simple roots of a root subsystem: positive (all E8 coordinates >= 0) and not a sum of two positives."""
    pos = [r for r in roots if positive(r)]
    pset = set(pos)
    out = []
    for p in pos:
        decomposable = any(tuple(a - b for a, b in zip(p, q)) in pset for q in pos if q != p)
        if not decomposable:
            out.append(p)
    return out


def components(roots):
    """Connected components of a root subsystem as sorted (rank, number of roots) pairs."""
    simple = simple_roots(roots)
    seen, comps = set(), []
    for i in range(len(simple)):
        if i in seen:
            continue
        stack, comp = [i], set()
        while stack:
            j = stack.pop()
            if j in comp:
                continue
            comp.add(j)
            stack.extend(k for k in range(len(simple)) if k not in comp and ip(simple[j], simple[k]) != 0)
        seen |= comp
        comps.append(comp)
    out = []
    for comp in comps:
        sub = [r for r in roots if _in_span(r, [simple[k] for k in comp], roots)]
        out.append((len(comp), len(sub)))
    return sorted(out)


def _in_span(r, simple, roots):
    # r in the root subsystem generated by `simple`: closure by reflections computed once per call set
    return r in _closure(tuple(simple))


_CACHE = {}


def _closure(simple):
    if simple in _CACHE:
        return _CACHE[simple]
    found, frontier = set(simple), list(simple)
    while frontier:
        new = []
        for beta in frontier:
            for s in simple:
                pairing = ip(beta, s)
                r = tuple(b - pairing * c for b, c in zip(beta, s))
                if r not in found:
                    found.add(r)
                    new.append(r)
        frontier = new
    full = found | {tuple(-x for x in r) for r in found}
    _CACHE[simple] = full
    return full


def neg(r):
    return tuple(-x for x in r)


def weights(r, base):
    return tuple(ip(r, s) for s in base)


def build_and_verify():
    roots = cl.roots_of_e8()
    rset = set(roots)
    basis = [tuple(1 if j == i else 0 for j in range(N)) for i in range(N)]

    # ---- D7 x U(1), D7 > D5 x D2, the frame-Higgs 40 ----------------------------------------
    level = {k: [r for r in roots if r[0] == k] for k in (-2, -1, 0, 1, 2)}
    d7 = level[0]
    d5_simple = [basis[i] for i in (1, 2, 3, 4, 5)]            # alpha_2 .. alpha_6: a D5 inside D7 (nodes 2..8)
    d5 = _closure(tuple(d5_simple))
    d5 = [r for r in d5 if r in rset]
    d2 = [r for r in d7 if all(ip(r, s) == 0 for s in d5_simple)]
    frame = [r for r in d7 if r not in set(d5) and r not in set(d2)]
    c_frame = Counter(weights(r, d5_simple) for r in frame)
    d2_simple = simple_roots(d2)
    c_frame_d2 = Counter(tuple(ip(r, s) for s in d2_simple) for r in frame)
    eq_frame = register(NAME, Equation(
        key="cl_frame_higgs", entry=ENTRY, title="The frame-Higgs 40 = (10, (2,2)) inside D7 over D5 x D2",
        source_kind="repo-doc", source=f"{THEORY} (match_e8_d7.py, check_frame_higgs.py), as the repository reads them",
        latex_str=(r"84=40+4+40,\qquad 40=(\mathbf{10},(\mathbf 2,\mathbf 2)),\qquad "
                   r"14=(\mathbf 1,\mathbf{10})+(\mathbf 4,\mathbf 1),\qquad 240=84+2\cdot 64+2\cdot 14"),
        notes="Read off the roots of E8: D7 is the set of roots with zero coefficient on node 1, D5 the roots on nodes "
              "2..6, D2 the roots of D7 orthogonal to that D5. The 40 roots left over carry the ten weights of the "
              "D5 vector, each four times, and four weights of the D2; the 14-root levels split as 10 + 4. This is the "
              "complex root system: it does not see the Lorentz signature or which su(2) factor is 'left'.",
    ))
    check(NAME, "the node 1 grading has 14, 64, 84, 64, 14 roots, so 240 = 84 + 2 . 64 + 2 . 14",
          [len(level[k]) for k in (-2, -1, 0, 1, 2)] == [14, 64, 84, 64, 14], eq=eq_frame)
    check(NAME, "nodes 2..6 span a D5 of 40 roots (rank 5), and the roots of D7 orthogonal to it form D2 = A1 x A1 with 4 roots",
          len(d5) == 40 and components(d5) == [(5, 40)] and len(d2) == 4 and components(d2) == [(1, 2), (1, 2)],
          eq=eq_frame)
    check(NAME, "the 84 roots of D7 are 40 + 4 + 40, the last 40 being the frame-Higgs generators",
          len(d5) + len(d2) + len(frame) == len(d7) == 84 and len(frame) == 40, eq=eq_frame)
    check(NAME, "the 40 carry ten distinct D5 weights, each four times: (10, 4 states)",
          len(c_frame) == 10 and set(c_frame.values()) == {4}, eq=eq_frame)
    check(NAME, "the same 40 carry four distinct D2 weights, each ten times: ((2,2), 10 states)",
          len(c_frame_d2) == 4 and set(c_frame_d2.values()) == {10}, eq=eq_frame)
    check(NAME, "jointly the 40 roots are in bijection with (D5 weight, D2 weight): all 40 pairs are distinct",
          len({(weights(r, d5_simple), tuple(ip(r, s) for s in d2_simple)) for r in frame}) == 40, eq=eq_frame)
    split = []
    for k in (2, -2):
        c5 = Counter(weights(r, d5_simple) for r in level[k])
        zero = tuple(0 for _ in d5_simple)
        n_zero = c5.get(zero, 0)
        d2_w = Counter(tuple(ip(r, s) for s in d2_simple) for r in level[k] if weights(r, d5_simple) == zero)
        split.append((len(c5) - (1 if zero in c5 else 0), n_zero, len(d2_w)))
    check(NAME, "each 14-root level is (1, 10) + (4, 1): ten roots of distinct nonzero D5 weight and four with D5 weight zero "
                "and distinct D2 weights",
          split == [(10, 4, 4), (10, 4, 4)], eq=eq_frame)

    # ---- E8 > D5 x A3, the branching of the adjoint -------------------------------------------
    a2_simple = [basis[2], basis[3]]                              # the family A2 of chirality_lisi: nodes 3 and 4
    e6 = [r for r in roots if all(ip(r, s) == 0 for s in a2_simple)]
    e6_simple = simple_roots(e6)
    d5_in_e6 = None
    for drop in range(len(e6_simple)):
        keep = tuple(s for k, s in enumerate(e6_simple) if k != drop)
        cl_ = _closure(keep)
        if len(cl_) == 40:
            d5_in_e6 = keep
            break
    d5e = _closure(d5_in_e6)
    a3 = [r for r in roots if all(ip(r, s) == 0 for s in d5_in_e6)]
    rest = [r for r in roots if r not in d5e and r not in set(a3)]
    a3_simple = simple_roots(a3)
    cls = {}
    for r in rest:
        cls.setdefault(weights(r, d5_in_e6), []).append(r)
    by_mult = Counter(len(v) for v in cls.values())
    # the D5 weight classes: a weight is in the root lattice class iff it is the weight of a D5 root; the vector weights
    # have norm 1, the spinor weights norm 5/4. Use the pairing of the weight with itself in D5 (via the Gram inverse).
    cart = sp.Matrix([[ip(a, b) for b in d5_in_e6] for a in d5_in_e6])
    inv = cart.inv()

    def wnorm(w):
        v = sp.Matrix(w)
        return (v.T * inv * v)[0]

    norms = Counter(wnorm(w) for w in cls)
    eq_su4 = register(NAME, Equation(
        key="cl_so10_su4", entry=ENTRY, title="E8 over SO(10) x SU(4): the adjoint branching, counted on roots",
        source_kind="repo-doc", source=f"{THEORY} (check_triality_su4.py: 'SU(4) = A3 centralizing SO(10)')",
        latex_str=(r"248=(\mathbf{45},\mathbf 1)+(\mathbf 1,\mathbf{15})+(\mathbf{10},\mathbf 6)+(\mathbf{16},\mathbf 4)"
                   r"+(\overline{\mathbf{16}},\overline{\mathbf 4}),\qquad 240=40+12+60+64+64"),
        notes="A D5 is taken inside the E6 of the family grading (the centraliser of the A2 of nodes 3 and 4). Its "
              "centraliser in E8 is an A3 (12 roots). The other 188 roots group by their D5 weight: ten vector weights "
              "of multiplicity 6, sixteen spinor weights of multiplicity 4 and sixteen conjugate ones of multiplicity 4. "
              "The dimensions then add: 45 + 15 + 60 + 64 + 64 = 248.",
    ))
    check(NAME, "E6 (the centraliser of the family A2) has 72 roots and rank 6; removing one of its simple roots leaves a D5 "
                "of 40 roots",
          len(e6) == 72 and len(e6_simple) == 6 and d5_in_e6 is not None and len(d5e) == 40, eq=eq_su4)
    check(NAME, "the centraliser of that D5 in E8 has 12 roots and is a single A3 (rank 3, determinant 4)",
          len(a3) == 12 and components(a3) == [(3, 12)] and sp.Matrix([[ip(a, b) for b in a3_simple] for a in a3_simple]).det() == 4,
          eq=eq_su4)
    check(NAME, "the other 240 - 40 - 12 = 188 roots carry 42 distinct D5 weights",
          len(rest) == 188 and len(cls) == 42, eq=eq_su4)
    check(NAME, "by multiplicity: 10 weights occur six times and 32 weights occur four times (10 x 6 + 32 x 4 = 188)",
          dict(by_mult) == {6: 10, 4: 32}, eq=eq_su4)
    check(NAME, "the ten weights of multiplicity six have norm 1 (the D5 vector) and the 32 others norm 5/4 (the two spinors)",
          all(wnorm(w) == 1 for w, v in cls.items() if len(v) == 6)
          and all(wnorm(w) == sp.Rational(5, 4) for w, v in cls.items() if len(v) == 4), eq=eq_su4)
    check(NAME, "dimensions: 45 + 15 + 10 . 6 + 16 . 4 + 16 . 4 = 248 and the roots 40 + 12 + 60 + 128 = 240",
          45 + 15 + 60 + 64 + 64 == 248 and 40 + 12 + 10 * 6 + 32 * 4 == 240, eq=eq_su4)

    # ---- A2 inside A3, and the A1 x A1 placements --------------------------------------------
    a2 = _closure(tuple(a2_simple))
    a2 = [r for r in a2 if r in rset]
    a3s = set(a3)
    # one pair of lines {+-r}, {+-s} per orthogonal pair of lines
    lines = []
    for r in a3:
        if r < neg(r):
            lines.append(r)
    ortho = [(r, s) for i, r in enumerate(lines) for s in lines[i + 1:] if ip(r, s) == 0]
    inside = [sum(1 for t in pair if t in set(a2) or neg(t) in set(a2)) for pair in ortho]
    eq_place = register(NAME, Equation(
        key="cl_su4_su3m", entry=ENTRY, title="The horizontal A2 lies in the A3 centraliser; each A1 x A1 shares exactly one A1 with it",
        source_kind="repo-doc", source=f"{THEORY} README.md 'Spin(1,3) against SU(3)_M'",
        latex_str=(r"\mathfrak{su}(3)_M\subset\mathfrak{su}(4)=Z_{E_8}(\mathfrak{so}(10)),\qquad "
                   r"\#\{\mathfrak{su}(2)\times\mathfrak{su}(2)\subset\mathfrak{su}(4)\}=3,\ \ "
                   r"|\mathfrak{su}(2)^2\cap\mathfrak{su}(3)_M|=1\ \text{each}"),
        notes="Counted on the roots of the A3. The A3 has six lines, which pair up into three orthogonal pairs; the A2 "
              "of the family grading contains three of the six lines, one from each pair. This is the root-level fact "
              "behind the repository's table of how the horizontal 3 and the spin doublet overlap. The table's "
              "'2 of 3 families in the physical 64' needs the Clifford construction and is not checked here.",
    ))
    check(NAME, "the family A2 (6 roots) lies inside the A3 that centralises the D5",
          len(a2) == 6 and all(r in a3s for r in a2), eq=eq_place)
    check(NAME, "the A3 has 12 roots = 6 lines, and 3 pairs of orthogonal lines",
          len(lines) == 6 and len(ortho) == 3 and len({tuple(sorted((p[0], p[1]))) for p in ortho}) == 3, eq=eq_place)
    check(NAME, "every line of the A3 is in exactly one orthogonal pair (so the three pairs partition the six lines)",
          sorted(l for p in ortho for l in p) == sorted(lines), eq=eq_place)
    check(NAME, "each orthogonal pair has exactly one line inside the A2 and one outside: [1, 1, 1]",
          inside == [1, 1, 1], eq=eq_place)
