#!/usr/bin/env python3
"""Run every model's checks and export all equations.

Usage (from sympy_models/ or the repo root):
    python3 sympy_models/export.py              # run all models, write build/
    python3 sympy_models/export.py on_scaling   # run selected models only (partial document)
    python3 sympy_models/export.py --pdf        # also build build/equations_document.pdf

Writes, under sympy_models/build/:
    equations.tex            one numbered equation per registered Equation (\\input-able, flat)
    equations.json           title, LaTeX, source, caveats and passed checks
    equations.md             quick human-readable index
    equations_summary.tex    summary table per CONTENTS entry   } \\input by the wrapper
    equations_by_entry.tex   one section per CONTENTS entry     } equations_document.tex
    concise_body.tex, concise_bibliography.tex                    } concise_document.tex (no tables)
With --pdf, pdflatex is run on equations_document.tex until references settle (the hand-editable wrapper).
Exit status is nonzero if any check fails, so nothing unverified is exported.
"""
import importlib
import json
import pkgutil
import re
import shutil
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import document  # noqa: E402
import eqlib  # noqa: E402
import models  # noqa: E402

CONTENTS = HERE.parent / "CONTENTS.md"
WRAPPER = "equations_document.tex"
CONCISE_WRAPPER = "concise_document.tex"


def build_pdf(out: Path, wrapper: str = WRAPPER) -> Path:
    """Run pdflatex (repeating until cross-references settle) from sympy_models/."""
    if shutil.which("pdflatex") is None:
        sys.exit("pdflatex not found (install TeX Live)")
    cmd = ["pdflatex", "-interaction=nonstopmode", "-halt-on-error",
           "-output-directory", str(out), wrapper]
    last = ""
    for _ in range(3):  # the table of contents and references usually settle after two runs
        run = subprocess.run(cmd, cwd=HERE, capture_output=True, text=True)
        last = run.stdout
        if run.returncode != 0:
            print(last[-3000:])
            sys.exit(f"pdflatex failed; see {out / (Path(wrapper).stem + '.log')}")
        if "Rerun to get" not in last:
            break
    pages = re.search(r"Output written on .*?\((\d+) pages?", last.replace("\n", ""))  # pdflatex wraps long paths
    pdf = out / (Path(wrapper).stem + ".pdf")
    print(f"built {pdf}" + (f" ({pages.group(1)} pages)" if pages else ""))
    return pdf


def discover(selected):
    names = [m.name for m in pkgutil.iter_modules(models.__path__)]
    if selected:
        unknown = set(selected) - set(names)
        if unknown:
            sys.exit(f"unknown model(s): {', '.join(sorted(unknown))}; have: {', '.join(names)}")
        names = [n for n in names if n in selected]
    return sorted(names)


def main(argv):
    want_pdf = "--pdf" in argv
    argv = [a for a in argv if a != "--pdf"]
    out = HERE / "build"
    out.mkdir(exist_ok=True)
    names = discover(argv)
    for name in names:
        mod = importlib.import_module(f"models.{name}")
        mod.build_and_verify()
        print(f"ok  {name}")

    eqs = list(eqlib.REGISTRY.values())
    tex = ["% Generated by sympy_models/export.py. Do not edit by hand.\n"]
    current = None
    for eq in eqs:
        if eq.model != current:
            current = eq.model
            tex.append(f"\n% ---- model: {current} ----\n")
        tex.append(eqlib.tex_block(eq))
    (out / "equations.tex").write_text("\n".join(tex))
    (out / "equations.json").write_text(json.dumps([e.to_dict() for e in eqs], indent=2))

    md = ["| key | entry | model | title | source |", "|---|---|---|---|---|"]
    md += [f"| `{e.key}` | {e.entry} | {e.model} | {e.title} | {e.source_kind}: {e.source} |" for e in eqs]
    (out / "equations.md").write_text("\n".join(md) + "\n")

    document.write(eqs, out, CONTENTS)

    n_checks = len(eqlib.checks())
    print(f"{len(eqs)} equations, {n_checks} checks passed -> {out}")
    if want_pdf:
        if argv:
            print(f"note: only {', '.join(names)} were run, so the document is partial")
        build_pdf(out)
        build_pdf(out, CONCISE_WRAPPER)


if __name__ == "__main__":
    main(sys.argv[1:])
